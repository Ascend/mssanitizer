// 型号、名单和前缀规则仅由 common 维护；hook 只转换协议类型并打印兜底提示。
inline DeviceType ResolveSocVersion(const std::string &socVersion) {
    const auto device = static_cast<DeviceType>(::GetDeviceTypeBySocVersion(socVersion));
    if (::GetExactProductTypeBySocVersion(socVersion) != ::ChipProductType::UNKNOWN_PRODUCT_TYPE) {
        return device;
    }
    if (device == DeviceType::ASCEND_910B_DEFAULT) {
        HOOK_LOG("Automatic SoC adaptation: soc=%s, target=ASCEND_910B_DEFAULT "
                 "(prefix match, representative specifications).",
            socVersion.c_str());
    } else if (device == DeviceType::ASCEND_950_DEFAULT) {
        HOOK_LOG("Automatic SoC adaptation: soc=%s, target=ASCEND_950_DEFAULT "
                 "(prefix match, representative specifications).",
            socVersion.c_str());
    }
    return device;
}

